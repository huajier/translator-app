using TranslatorApp.Core.Abstractions;

namespace TranslatorApp.Core.Capture;

internal sealed partial class OcrTextCapture : ITextCapture
{
    /// <summary>
    /// 置信度达到多少，就算「这个模型认得很确定」，不必再试另一种语言。
    ///
    /// 【2026-10-09 数值来自用户实测数据，不是拍脑袋】
    ///   同一批内容、同一套引擎，只换模型，置信度差得非常干净：
    ///     真英文配 eng 模型 → **0.9**
    ///     俄文配   eng 模型 → **0.1 ~ 0.4**
    ///
    ///   0.75 卡在中间那片空白里：
    ///   离 0.4 有余量（俄文绝不会被误判成「英文很确定」），
    ///   离 0.9 也有余量（稍差的英文不会白白多跑一次俄文）。
    /// </summary>
    private const double GoodConfidence = 0.75;

    /// <summary>
    /// 【2026-10-27 阶段三 S3】RapidOCR 主通道的及格线：各检测行的平均字置信度。
    ///
    ///   低于它就**不信新引擎**，整条回退旧通道（Windows OCR + Tesseract 多路）。
    ///   为什么要有这道线：新引擎「几乎不再整行丢」，但它对**纯噪声/半截字**
    ///   同样会吐出一行低分文字；没有这道线，那种垃圾会被当成结果交出去。
    ///
    ///   【0.55 怎么来的】
    ///     引擎自己默认 TextScore=0.5 已经把整行平均分低于 0.5 的行丢掉；
    ///     0.55 只比它高一点点，含义是「引擎留下了，而且不像噪声」。
    ///     首轮 121 行 A/B 的实测分布见 tools\日志\阶段3-S3-集成AB.md。
    ///
    ///   ponytail: 单一阈值，没按游戏/极性分档；样本够了再拆。
    /// </summary>
    private const double RapidOcrMinScore = 0.55;

    /// <summary>
    /// 【2026-11-07】RapidOCR 主通道的「字数量闸门」：采信前至少要认出这么多个有效字符。
    ///
    ///   低于它 → 视为**没认出来**，回退旧通道（Windows OCR + Tesseract 多路），
    ///   和「没认出字」走同一条路，回退分支一行代码都不用改。
    ///
    ///   【为什么必须有这道线】
    ///     RapidOcrMinScore（0.55）只管「分数」，不管「认出了几个字」。
    ///     一个孤零零的 `c` 平均分也能到 0.59，于是直接 return，
    ///     把后面已经读到 32 个字的 Tesseract 顶掉。
    ///
    ///   【为什么是 2，不是 3、不是分数】
    ///     2026-11-07 全量回放 331 张，15 段失败**全部**是同一模式：
    ///       RapidOCR 只认到 0~1 个字就采纳（13 段 1 个字、2 段 0 个字），
    ///       且这 15 段在 10-26 那次回放里全对（那天走了 Tesseract）。
    ///     今天 1,867 个样本 + 历史日志 10,586 个样本交叉验证：
    ///       认到 0~1 个字的样本 60 次，**最终成功 0 次** —— 这条路上一次都没对过。
    ///     反向防误杀：认到 2~3 个字却被采纳的样本里成功 11 段
    ///       （行-69 认 2 字/0.93、行-70 认 3 字/1.00、材料2-R7-3 认 3 字/0.58 等），
    ///       那些是 UI 上真正的短文本（Back / ON / PER），**不能动**。
    ///     所以分界线在「几个字」，卡在 2：0~1 挡掉，2 及以上一个字节都不改。
    ///
    ///   ponytail: 单一门槛；若以后出现「认 2 个字却该回退」的样本，再按框/语言细分。
    /// </summary>
    private const int RapidOcrMinChars = 2;

    /// <summary>
    /// 「兜底尝试」的门槛，**比择优门槛更保守（更高）**。
    ///
    /// 【为什么不能两个都用 0.75（用户实测踩出来的）】
    ///   Z1 那张橙底绿字的中文，外文模型只认出 `SVMs`（4 个字），
    ///   置信度 **0.76**——**就比 0.75 高一点点**，
    ///   中文兜底因此完全没被触发，结果四个字交到了用户面前。
    ///
    ///   置信度高**不等于内容对**：
    ///   图上只剩几根杂碎笔画时，Tesseract 会「很自信地」把它认成几个像样的字，
    ///   分数自然就高。**越是这种看着「还挺确定」的小结果，越要多问一句。**
    ///
    ///   定 0.90：实测里真正认对了的外文都在 0.81~0.95，
    ///   门槛放在 0.90 意味着**只有接近完美的结果才免去这道兜底**，
    ///   多花的那 30 毫秒换掉「四个字糊弄过去」的惨剧，很划算。
    /// </summary>
    private const double GoodConfidenceForRescue = 0.90;

    /// <summary>
    /// 【2026-10-15 路二第二步（Z1）】「垫底分低到这个数以下」才算可疑。
    ///
    /// 【为什么是 70】
    ///   Z1（`今天天气不错适合出门`）那条路实测 12 次，
    ///   多出来的那个「和」自报 **63 ~ 66.84**，
    ///   而同句第二低的字是 **88.51 ~ 92.48**——
    ///   中间隔着 20 多分的空档，70 落在空档正中，两头都留了余量。
    ///   离线对拍：60 一次都不出手（捞不着），65 只捞回一半，70 起满额。
    ///
    /// ponytail: 阈值是「实测空档」定的，不是拍脑袋；样本多了要重看。
    /// </summary>
    private const double LowWordScoreCeiling = 70.0;

    /// <summary>
    /// 【2026-10-15 路二第二步（Z1）】垫底分还得**比第二低拉开 15%** 才算可疑。
    ///
    ///   只看「低于 70」不行：一句话里所有字都只有 60 分时，
    ///   最低的那个并不特别，删了就是瞎猜。实测 Z1 的比例是
    ///   63.37 / 89.05 ≈ 0.71，离 0.85 很远；设 0.85 是留足余量。
    /// </summary>
    private const double LowWordScoreRatio = 0.85;

    /// <summary>
    /// 「这段文字算不算俄文」的门槛：**西里尔字母至少要占 50%**。
    ///
    /// 【为什么不是 0.10（用户实测数据定出来的）】
    ///   放大到 4 倍之后 `rus+eng` 分数普遍变高，
    ///   E3（**英文**）被 rus+eng 以 0.92 顶掉 eng 的 0.91，
    ///   英文邮箱被拼成了西里尔 `те@ехатре.сот`。
    ///
    ///   把那一轮每段的西里尔占比拉出来：
    ///     认对的俄文 → R7 87%、R8 78%、R9 90%、其余全部 100%
    ///     认错的 E3  → **20%**
    ///   **正确的一律 78% 以上，错误的那个只有 20%，中间一大片空白。**
    ///   0.50 卡在空白正中间，不存在「卡在哪都可能出错」的问题。
    ///
    /// 【道理】
    ///   真正的俄文句子，字母里绝大多数是西里尔；
    ///   「把英文硬拼成西里尔」的产物，西里尔只集中在被误认的那几个词里，占比很低。
    /// </summary>
    private const double MinCyrillicRatioForRussian = 0.50;

    /// <summary>
    /// 俄文这一票里，**拉丁同形字**占比超过这个数，就判定它是在瞎拼英文，不采用。
    ///
    /// 【场景（2026-10-24 用户手测实测）】
    ///   Tesseract 的 eng 模型把 `BATTLEBOARD` 读坏（0.19 / 0.36），
    ///   rus 模型分数更高（0.41 / 0.50）于是被锁成 rus，
    ///   结果四路全用俄文模型跑，吐出一串 `ВАТТЦЕВОАВО»`——
    ///   内容是「把 BATTLEBOARD 按字母形状译成西里尔」的假货，
    ///   最高只有 0.28 分，最后整段判乱码、取词失败。
    ///
    ///   `CountCyrillicRatio` 拦不住它：假西里尔的西里尔占比是 **100%**。
    ///   能分开的是「同形字占比」——真俄文有大量 ш/щ/ж/ы/э 这类非同形字母。
    ///
    /// 【阈值怎么定的，有数据】
    ///   跑遍 7 个日志文件（2178 个真俄文块 / 711 个假西里尔块）扫阈值：
    ///     0.50 → 误伤 0，拦住 561；0.75 → 误伤 0，拦住 274；0.90 → 误伤 0，拦住 109。
    ///   取 0.75：既零误伤，又给「真俄文里夹 ООО 公司名」这种留了余量。
    /// </summary>
    private const double MaxCyrillicHomoglyphRatioForRussian = 0.75;

    /// <summary>
    /// 【2026-11-10 用户实测补】cyrillic 模型比 en 模型自信多少，才值得改用它的结果：0.05。
    ///
    /// 【为什么需要这条】en 模型把俄文拼成形似拉丁的字符时（С→C、т→T、а→a），
    ///   产出的结果「看起来像正常英文」：词内混排比 0.00、长度和 cyr 差不多，
    ///   原来两条老判据（混排 ≥0.15 / 长度少 20%）一条都命中不了，
    ///   于是保了 en，用户看到的是乱码。
    ///   实测样本：Старые хиты → en `CTapble xitbl`(0.823) vs cyr `Старые хиты`(0.971)，
    ///   差 0.148；而真英文图上这个差值通常是负的（en 比 cyr 自信）。
    ///
    /// 【为什么是 0.05（离线扫出来的，别自己调）】
    ///   conf 差 >=0.00/0.02/0.05/0.08/0.10 → 短俄文都是 6/9、行级 65/80；
    ///   配合老条件后 0.05/0.08/0.10 都是短俄文 9/9、俄文段 10/11、行级一格不掉；
    ///   0.15 就掉到 6/9 了。取 0.05 = 能过线的最小值，给新字体留余量。
    /// </summary>
    private const double CyrillicConfidenceMargin = 0.05;

    /// <summary>
    /// **低于这个分数就当没认出来**，绝不把乱码当正式结果给用户。
    ///
    /// 【这道门槛从 0.60 提到 0.78 —— 材料 3 把空档填清楚了】
    ///
    ///   当初定 0.60 的办法是「找认对和认错之间的空档，卡在中间」。
    ///   那时手上的样本是：
    ///     认对的：0.81 ~ 0.96
    ///     认错的：0.08 ~ 0.46
    ///     中间 0.46 ~ 0.81 什么都没有，所以 0.60 卡在中间。
    ///
    ///   **材料 3 之后，空档里掉进来两个新样本，全是乱码**：
    ///     `Масппе {гап|айоп сопуей$ {ех тот опе |апдцаде © апо{ег.`   0.70
    ///     小灰字那段 `这一切专| J亲六革路刚队急材衬宫人小由有加了息…`    0.57
    ///   **0.70 从 0.60 那道门槛底下钻过去了，正是用户看到乱码的原因。**
    ///
    ///   现在的完整分布：
    ///     认成乱码的：0.13  0.32  0.33  0.57  0.70  0.76
    ///     ────────────────────────────────
    ///                                        ↑ 0.76 ~ 0.81 又是空的
    ///     认对了的：0.81  0.85  0.86  0.87  0.88  0.93  0.94  0.95  0.96
    ///   **0.78 卡在新的空档里，用的还是当初那个办法。**
    ///
    /// 【2026-10-10 用户问「能不能识别出乱码的时候返回未识别到文字」】
    ///   这是用户亲口提的要求：**宁可说没认出来，也不要给一堆乱码。**
    ///   代价是偶尔会拒掉一些其实还能看的结果——**这个代价用户自己认了**。
    ///
    /// 【两条走不通的路，已经用实测数据否掉，别再走】
    ///   ① **靠文本形态判断乱码**——不可靠。
    ///      实测符号占比：正常技术文本 `HTTP/2.0 … 85% CPU` 是 **0.19**，
    ///      乱码 `Масппе {гап|айоп сопуей$` 是 **0.16**，**乱码反而更低，分不开**。
    ///      而且 `{ } | $ ©` 在正常代码和文档里本来就大量出现。
    ///   ② **靠「两个引擎结果一致」判断可信**——也不可靠。
    ///      实测那一段乱码：`rus` 和 `rus+eng` 给出**一模一样的 0.70 / 64 字**，
    ///      一致度 100%，**结果还是错的**。两个引擎会一致地错。
    ///   **目前唯一被数据支持的信号，还是置信度。**
    /// </summary>
    private const double MinimumAcceptableConfidence = 0.78;

    /// <summary>
    /// 英文第二票的「分数护栏」：第一票已经够格（≥ MinimumAcceptableConfidence）、
    /// 第二票却比它低这么多时，**不换票**，保留第一票。
    ///
    /// 【为什么要有这条（2026-10-17，用户报的 BATTLEBOARD 错例）】
    ///   换票的四条路只看「两份内容对不对得上」，不看第二票读得好不好。
    ///   路子①「字母数字一模一样」在同长度时也成立，于是
    ///   `BATTLEBOARD`（0.90，一个字母都没错）被 `BATTLEBOARD:`（0.28）换掉，
    ///   之后四路择优又选中一版 0.70 的，低于 0.78 → 整块判乱码扔掉。
    ///
    /// 【0.10 是怎么定的】
    ///   历史 333 次换票里，符合「第一票 ≥0.78 且第二票低 ≥0.10」的只有 **2 次**：
    ///     ① 2026-10-17 13:03:09  `0.90 → 0.28`   BATTLEBOARD（救回，原本被扔掉）
    ///     ② 2026-10-17 10:17:01  `0.82 → 0.66`   Issues is:issue（结果不变，四路救回）
    ///   325 次换票的分数变化都在 ±0.16 以内，**0.10 这条线不会误伤正常换票**。
    ///   不要把这条线调小（0.05 会开始拦「第二票略差但内容更全」的正常情况），
    ///   也不要调大（0.20 以上就拦不住 0.28 这种暴跌）。
    /// </summary>
    private const double SecondVoteScoreDropLimit = 0.10;

    /// <summary>
    /// 四路二值图的顺序说明，只用于把日志写成人能看懂的话。
    /// 顺序必须和 ImagePreprocessor.PrepareAllPlanes 的返回顺序一致。
    /// </summary>
    private static readonly string[] PlaneNames = ["红通道", "绿通道", "蓝通道", "灰度", "局部阈值"];

}
